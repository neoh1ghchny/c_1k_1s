/**
 * a(n) = (-1)^n * x^(2n/3)/(2n)!
 * a(n+1) = (-1)^(n+1) * x^(2(n+1)/3)/(2(n+1))!
 * a(n+1) = (-1)^(n+1) * x^((2n+2)/3)/(2n+2)!
 *
 *                      (-1)^(n+1)  x^((2n+2)/3)    (2n)!
 * q(n) = a(n+1)/a(n) = ---------- ------------- ---------
 *                       (-1)^n     x^(2n/3)    (2n+2)!
 *
*                       -(-1)^n  x^(2n/3) x^(2/3)    (2n)!
 * q(n) = a(n+1)/a(n) = ---------- -------------    ---------
 *                       (-1)^n     x^(2n/3)        (2n+2)(2n+1)(2n)!
 *
 *  ([]+1)!=([]+1)([])!
 *  (2n+2)!=(2n+2)(2n+1)! = (2n+2)(2n+1)(2n)!
 *
*                       -x^(2/3)
 * q(n) = a(n+1)/a(n) = ----------
 *                      (2n+2)(2n+1)
 *
*                  x^(2/3)
 * a(n+1) = -a(n) ----------
 *                 2(n+1)(2n+1)
 *
 * a(0) = 1
 */

int main()
{
    int N = 5;

    double x = 1.5, a = 1.0, S = 0.0;

    int n;

    for (n = 0; n < N; ++n)
    {

       double q = -cbrt(x * x)/2.0/(n + 1.0)/(2.0 * n + 1);

       a *= q;

       S += a;
    }

    double etalon = cos(cbrt(x));

    printf("Etalon: %.5f\n", etalon);

    printf("Sum of series: %.5f\n", S);

    return 0;
}
